import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const KEY = 'back-to-strong.v1'
const read = (page: Page) => page.evaluate(key => JSON.parse(localStorage.getItem(key) || '{}'), KEY)
async function nav(page: Page, name: string) {
  await page.getByRole('navigation', { name: /navigation/ }).filter({ visible: true }).getByRole('button', { name, exact: true }).first().click()
}
async function onboard(page: Page, concern = false) {
  await page.getByRole('button', { name: 'Build my plan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'What brings you back?' })).toBeVisible()
  await page.getByRole('button', { name: 'Build consistency', exact: false }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: '20 minutes' }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  if (concern) await page.getByRole('button', { name: 'I have pain, an injury, or a medical restriction' }).click()
  await page.getByRole('button', { name: 'Create my plan' }).click()
  if (!concern) await page.getByRole('button', { name: 'Skip walkthrough' }).click()
}
async function log(page: Page, set: number, weight = '') {
  await page.getByRole('spinbutton', { name: `Set ${set} repetitions`, exact: true }).fill('8')
  if (weight) await page.getByRole('spinbutton', { name: `Set ${set} weight in kilograms`, exact: true }).fill(weight)
  await page.getByRole('button', { name: `Log set ${set}`, exact: true }).click()
}

