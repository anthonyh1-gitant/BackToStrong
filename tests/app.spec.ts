test('corrupt data is preserved, failed saves are honest, and offline reload recovers logs', async ({ page, context }) => {
  await page.goto('./')
  await page.evaluate(key => localStorage.setItem(key, '{broken'), KEY)
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('could not be read')
  expect(await page.evaluate(key => localStorage.getItem(key), KEY)).toBe('{broken')
  await nav(page, 'Settings')
  await page.getByRole('button', { name: 'Delete all local data' }).click()
  await page.getByRole('button', { name: 'Yes, delete my data' }).click()
  await onboard(page)
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Set 1 repetitions', exact: true }).fill('8')
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Object.assign(window, { restoreStorage: () => { Storage.prototype.setItem = original } })
    Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError') }
  })
  await page.getByRole('button', { name: 'Log set 1', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('could not be saved')
  expect((await read(page)).active.exercises[0].sets[0].done).toBe(false)
  await page.evaluate(() => (window as unknown as { restoreStorage: () => void }).restoreStorage())
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Undo set 1' })).toBeVisible()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await expect.poll(async () => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Leg press', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Undo set 1' })).toBeVisible()
  await expect(page.getByText('You’re offline. Your plan and logs stay on this device.')).toBeVisible()
  await context.setOffline(false)
})
